CREATE TABLE `careerProfiles` (
	`id` int AUTO_INCREMENT NOT NULL,
	`userId` int NOT NULL,
	`fullName` varchar(160),
	`age` int,
	`education` varchar(80),
	`degree` varchar(180),
	`careerStatus` varchar(32),
	`currentJob` varchar(180),
	`company` varchar(180),
	`lookingFor` varchar(80),
	`careerField` varchar(120),
	`targetRole` varchar(180),
	`skills` text,
	`experience` text,
	`resumeKey` varchar(500),
	`resumeUrl` varchar(500),
	`resumeName` varchar(260),
	`resumeSize` int,
	`resumeMimeType` varchar(120),
	`personalizationEnabled` boolean NOT NULL DEFAULT true,
	`jobRecommendationsEnabled` boolean NOT NULL DEFAULT true,
	`professionalConnectionsEnabled` boolean NOT NULL DEFAULT true,
	`isComplete` boolean NOT NULL DEFAULT false,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `careerProfiles_id` PRIMARY KEY(`id`),
	CONSTRAINT `careerProfiles_userId_unique` UNIQUE(`userId`)
);
